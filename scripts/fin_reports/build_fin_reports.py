"""Builds, from fin_report_data.py:
  scripts/fin_reports/out/fin_reports_part0..N.sql   (table manufacturer_fin_report_sales + sales_manufacturers_year.sales_from_fin_reports)
  assets/manufacturer-fin-report-sales.js              (FIN_REPORT_SALES, read by manufacturers.html)
Run from the repo root:  python scripts/fin_reports/build_fin_reports.py
Also prints sanity checks (regional rows vs world total).
"""
import json, os, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
from fin_report_data import ENT, ROWS  # noqa: E402


def q(v):
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def checks():
    world = {}
    reg = defaultdict(int)
    keys = set()
    for ent, y, pt, st, en, region, seg, units, basis, scope, conf, src, url, notes, additive in ROWS:
        k = (ent, y, pt)
        if seg == 'All' and region == 'World':
            world[k] = units
        elif seg == 'All' and additive:
            reg[k] += units
    for k, tot in sorted(world.items()):
        if k in reg:
            d = reg[k] - tot
            flag = 'OK ' if abs(d) <= max(3000, tot * 0.001) else 'GAP'
            print(f'  {flag} {k[0][:38]:38s} {k[1]} {k[2]:3s} world {tot:>10,} regions {reg[k]:>10,} diff {d:>+8,}')
    # duplicates on the table's unique key
    seen = set()
    for r in ROWS:
        key = (r[0], r[1], r[2], r[5], r[6])
        if key in seen:
            print('  DUPLICATE KEY', key)
        seen.add(key)
    print(len(ROWS), 'rows,', len({r[0] for r in ROWS}), 'entities')


DDL = """
create table if not exists public.manufacturer_fin_report_sales (
  id bigint generated always as identity primary key,
  manufacturer text not null,
  parent_group text,
  reporting_level text,            -- 'group' | 'subsidiary' (subsidiary rows are already inside their group: do not add both)
  year integer not null,           -- calendar year; for fiscal-year reporters the year the FY starts (FY2025 = Apr 2025-Mar 2026)
  period_type text not null,       -- 'CY' | 'FY' | '9M'
  period_start date,
  period_end date,
  calendar_aligned boolean not null,
  region text not null default 'World',
  segment text not null default 'All',
  units bigint not null,
  units_basis text,                -- deliveries | retail | wholesale | shipments
  scope text,
  additive boolean not null default true,   -- false = memo line already included in another region row
  confidence text,                 -- filing | press_release | media | derived
  source_doc text,
  source_url text,
  notes text,
  date_updated date not null default current_date,
  unique (manufacturer, year, period_type, region, segment)
);
comment on table public.manufacturer_fin_report_sales is 'Worldwide sales per manufacturer as REPORTED by the companies (annual reports, 10-K/20-F/6-K, results and year-end sales releases), with regional splits where the company publishes them. These are the real world totals, as opposed to the sum of the countries tracked on this site. Basis (deliveries/retail/wholesale/shipments) and scope differ by company and are not interchangeable. Generated by scripts/fin_reports/build_fin_reports.py from scripts/fin_reports/fin_report_data.py.';
alter table public.manufacturer_fin_report_sales enable row level security;
alter table public.sales_manufacturers_year add column if not exists sales_from_fin_reports bigint;
alter table public.sales_manufacturers_year add column if not exists fin_reports_basis text;
comment on column public.sales_manufacturers_year.sales_from_fin_reports is 'World total sales of the manufacturer for the year as reported in its financial reports / official sales releases (calendar year preferred, else fiscal year starting that year). Detail, regions and sources: table manufacturer_fin_report_sales.';
"""


def migration_parts(n_chunks=3):
    """DDL + the fact rows in chunks (source doc/url pairs are factored into a per-chunk CTE to keep each statement small)."""
    parts = [DDL.strip() + '\n']
    cols = '(manufacturer,parent_group,reporting_level,year,period_type,period_start,period_end,calendar_aligned,region,segment,units,units_basis,scope,additive,confidence,source_doc,source_url,notes)'
    per = -(-len(ROWS) // n_chunks)
    for i in range(0, len(ROWS), per):
        chunk = ROWS[i:i + per]
        srcs = {}
        vals = []
        for ent, y, pt, st, en, region, seg, units, basis, scope, conf, src, url, notes, additive in chunk:
            grp, level, *_ = ENT[ent]
            k = srcs.setdefault((src, url), 's%d' % len(srcs))
            vals.append('(' + ','.join([q(ent), q(grp), q(level), q(y), q(pt), q(st), q(en), q(pt == 'CY'), q(region), q(seg), q(units), q(basis), q(scope or None), q(additive), q(conf), q(k), q(notes or None)]) + ')')
        cte = 'with src(k,doc,url) as (values ' + ','.join('(%s,%s,%s)' % (q(k), q(d), q(u or None)) for (d, u), k in srcs.items()) + ')\n'
        ins = ('insert into public.manufacturer_fin_report_sales ' + cols + '\n' + cte
               + 'select v.manufacturer,v.parent_group,v.reporting_level,v.year,v.period_type,v.period_start::date,v.period_end::date,v.calendar_aligned,v.region,v.segment,v.units,v.units_basis,v.scope,v.additive,v.confidence,src.doc,src.url,v.notes\n'
               + 'from (values\n' + ',\n'.join(vals) + '\n) as v(manufacturer,parent_group,reporting_level,year,period_type,period_start,period_end,calendar_aligned,region,segment,units,units_basis,scope,additive,confidence,srck,notes)\n'
               + 'join src on src.k = v.srck\n'
               + 'on conflict (manufacturer, year, period_type, region, segment) do update set units=excluded.units, units_basis=excluded.units_basis, scope=excluded.scope, additive=excluded.additive, confidence=excluded.confidence, source_doc=excluded.source_doc, source_url=excluded.source_url, notes=excluded.notes, date_updated=current_date;')
        parts.append(ins + '\n')
    # world totals into sales_manufacturers_year (one row per entity-year; CY preferred over FY)
    best = {}
    for ent, y, pt, st, en, region, seg, units, basis, scope, conf, src, url, notes, additive in ROWS:
        if region == 'World' and seg == 'All' and pt in ('CY', 'FY'):
            k = (ent, y)
            if k not in best or (pt == 'CY' and best[k][0] != 'CY'):
                best[k] = (pt, units, basis, src, url, conf, notes)
    sv = []
    for (ent, y), (pt, units, basis, src, url, conf, notes) in sorted(best.items()):
        grp, level, country, region, _ = ENT[ent]
        src_txt = f'{src} [{conf}{"; fiscal year Apr-Mar" if pt == "FY" else ""}]'
        sv.append('(' + ','.join([q(y), q(region), q(country), q(ent), q(units), q(basis), q(src_txt), q(url or None)]) + ')')
    parts.append('insert into public.sales_manufacturers_year (year,manufacturer_region,manufacturer_country,manufacturer,sales_from_fin_reports,fin_reports_basis,sources,notes) values\n'
                 + ',\n'.join(sv) + '\non conflict (year, manufacturer) do update set sales_from_fin_reports=excluded.sales_from_fin_reports, fin_reports_basis=excluded.fin_reports_basis, sources=excluded.sources, notes=excluded.notes, date_updated=current_date;\n')
    return parts


def asset():
    """FIN_REPORT_SALES = { entities:[{name, group, level, sites:[site group names], rows:{'2025':{ptype:'CY', units, basis, conf, regions:[...]}}}] }"""
    ents = []
    for name, (grp, level, country, region, sites) in ENT.items():
        rows = [r for r in ROWS if r[0] == name]
        if not rows:
            continue
        years = {}
        for ent, y, pt, st, en, reg, seg, units, basis, scope, conf, src, url, notes, additive in rows:
            if pt not in ('CY', 'FY'):
                continue
            d = years.setdefault(str(y), {})
            if reg == 'World' and seg == 'All':
                if 'units' not in d or (pt == 'CY' and d.get('pt') != 'CY'):
                    d.update(pt=pt, units=units, basis=basis, conf=conf, src=src, url=url, scope=scope)
            elif seg == 'All' and pt == d.get('pt', pt):
                d.setdefault('regions', []).append({'r': reg, 'u': units, 'add': additive})
        years = {y: d for y, d in years.items() if 'units' in d}
        if years:
            ents.append({'name': name, 'group': grp, 'level': level, 'sites': sites, 'years': years})
    js = ('// Worldwide sales per manufacturer as reported in the companies\' financial reports / official sales releases.\n'
          '// Generated by scripts/fin_reports/build_fin_reports.py from scripts/fin_reports/fin_report_data.py -- Supabase table manufacturer_fin_report_sales.\n'
          '// pt: CY calendar year | FY fiscal year starting that year (Apr-Mar). conf: filing | press_release | media | derived. Units basis differs by company.\n'
          'const FIN_REPORT_SALES = ' + json.dumps(ents, ensure_ascii=False, separators=(',', ':')) + ';\n')
    return js


if __name__ == '__main__':
    checks()
    os.makedirs(os.path.join(HERE, 'out'), exist_ok=True)
    parts = migration_parts()
    sql = '\n'.join(parts)
    for i, ptxt in enumerate(parts):
        open(os.path.join(HERE, 'out', 'fin_reports_part%d.sql' % i), 'w', encoding='utf8').write(ptxt)
    open(os.path.join(ROOT, 'assets', 'manufacturer-fin-report-sales.js'), 'w', encoding='utf8').write(asset())
    print('sql', len(sql), 'bytes')
