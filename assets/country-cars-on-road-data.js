// world_auto_sales_annual new-registration counts with cars_duration_rate survival curves,
// anchored to real observed stock-by-fuel data (KBA FZ13 for Germany, SSB table 11823 for
// Norway) wherever it exists. See that table's column comments for full methodology.
//
// method per row:
//   REAL                              = directly observed official stock-by-fuel-type figure.
//   MODEL_RAW_PREREAL                 = pure survival-curve convolution, used only before any
//                                       real stock-by-fuel data exists for that country (BEV is
//                                       negligible in this era regardless).
//   MODEL_ANCHORED                    = survival-curve convolution projected forward from the
//                                       last REAL year, rescaled to match it, assuming NO new
//                                       registrations after the last known registration year.
//   MODEL_ANCHORED_WITH_FUTURE_REG    = as above, but for 2027-2041 also adds newly-registered
//                                       cohorts each year, sized by `futureNewRegProj` (see
//                                       below) and its implied BEV count (constant total minus
//                                       that), each aged by the same survival curve from its own
//                                       registration year forward. Germany/Norway only.
//   MODEL_PROJECTED_WITH_FUTURE_REG   = same idea as MODEL_ANCHORED_WITH_FUTURE_REG, for the 29
//                                       countries that have no REAL stock anchor. Superseded
//                                       2026-09-14 (see below) after the first version of this
//                                       batch produced impossible results (non-BEV registrations
//                                       clamped to exactly 0 for 20 of the 29 countries within a
//                                       few years, because it CAGR'd total-market size and BEV
//                                       count independently for 15 years with only "BEV capped at
//                                       total" as a backstop).
//
// Corrected 2026-09-14: for the 29 non-anchored countries, future years (2027-2041) now model
// BEV's SHARE of new registrations on a logistic (odds-ratio) curve instead of extrapolating raw
// BEV/non-BEV counts directly -- share = odds/(1+odds), so it can approach but never reach 0% or
// 100%, which a plain exponential on the counts themselves cannot guarantee (that's what let BEV
// exceed the entire market, or non-BEV get squeezed to exactly 0, in the superseded version).
// Total registrations are held CONSTANT at the last real/projected year (2026 for most countries;
// 2025 for Russian Federation and South Africa, which have no 2026 figure yet). The odds-ratio's
// annual growth rate is taken from the real BEV-share change over that country's own 2024->2026
// window (2023->2026 for the Philippines, whose 2024 BEV figure wasn't usable), then DECAYED with
// a 6-year half-life for years beyond the window -- so the near-term trend is honored without
// compounding an often-extreme 2-year growth rate at a constant clip for the full 15 years (e.g.
// Argentina's real BEV share grew from 0.14% to 1.5% in that window, an odds-growth rate over
// 200%/yr that would otherwise imply near-total EV conversion within a decade). Each country's
// 2027 value is anchored to its own real 2026 (or 2025) stock figure so there is no discontinuity
// at the projection boundary. Full per-country figures (share start/end, growth rate, total held
// constant) are in country_cars_on_road's own row notes.
// Registration history for these 29 countries: BEV/total split comes from this project's own
// annual powertrain data (varies by country, as early as 2013, as late as 2023); years before
// that use auto-markets-by-country.html's MARKETS.series total-market figures (2005 onward for
// most countries, BEV assumed 0) with no independent BEV number: pre-2013 EV volume is genuinely
// close to zero almost everywhere, so this is a reasonable simplification, not a real gap. Taiwan
// has no MARKETS.series data before 2020 at all -- its 2005-2019 rows flat-backfill the 2020
// figure rather than inventing a trend, per explicit user instruction to do this only where no
// real data could be found. Continent-to-survival-curve mapping: EU->Europe, ASIA->Asia,
// NAC (US/Canada)->America, SA->Latam; Mexico (NAC) and South Africa (AFRICA) were mapped to
// Latam and Australia (OCEANIA) to America as the closest available proxies -- this project's
// cars_duration_rate table only has America/Europe/Latam/Asia curves plus Germany's and Norway's
// own (Germany's is identical to the generic Europe curve; only Norway's is genuinely distinct).
// futureNewRegProj: for Germany/Norway, projected NEW non-BEV registrations for that year; for
// the other 29 countries, projected NEW non-BEV registrations implied by the logistic BEV-share
// curve described above (non-BEV = total_const * (1 - bevShare)).
//   Germany: nonbev_2026 * (1+CAGR)^(year-2026), CAGR = compound annual growth rate of non-BEV
//   registrations from 2024 to 2026 (ACEA annual/projected figures) = -3.49%/yr.
//   Norway: same CAGR formula for 2027 only (CAGR -46.4%/yr, reflecting its near-total EV
//   transition); 2028 onward is floored to exactly 0 rather than left to asymptotically decay,
//   since Norway's BEV share is already 98%+ and treating the last sliver of non-BEV sales as
//   fully gone by 2028 is a reasonable simplification at that point.
//   Total registrations are held CONSTANT at the 2026 level; projected BEV registrations for
//   that year = constant total - futureNewRegProj.
