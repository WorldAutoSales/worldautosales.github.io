// On-road passenger-car fleet estimates (BEV vs non-BEV), by country and year, 2005-2041.
// Source: Supabase `country_cars_on_road` (project rtmlxvjpjxcvjdykrkvm), built by convolving
// world_auto_sales_annual new-registration counts with cars_duration_rate survival curves,
// anchored to real observed stock-by-fuel data (KBA FZ13 for Germany, SSB table 11823 for
// Norway) wherever it exists. See that table's column comments for full methodology.
//
// method per row (historical, years <= each country's anchor year -- unchanged by the 2026-09-15
// rework below):
//   REAL                 = directly observed official stock-by-fuel-type figure.
//   MODEL_RAW_PREREAL    = pure survival-curve convolution, used only before any real
//                          stock-by-fuel data exists for that country (BEV is negligible in
//                          this era regardless).
//   MODEL_ANCHORED       = survival-curve convolution projected forward from the last REAL year,
//                          rescaled to match it, assuming NO new registrations after the last
//                          known registration year.
//
// MODEL_STOCK_CONSTANT_WITH_FUTURE_REG = every future year (anchor_year+1 .. 2041, for all 33
// countries, superseding the two now-retired FUTURE_REG methods this project used earlier).
// Denmark and Singapore were added 2026-09-15 directly with this method (built with the same
// pure survival-curve convolution back to 2005 the other MODEL_RAW_PREREAL countries used for
// their historical rows, then this method for the future ones) -- they never had the superseded
// versions below.
// Corrected 2026-09-15 after both prior approaches proved wrong: the total ON-ROAD STOCK
// (bev+nonBev) is now held EXACTLY CONSTANT at the anchor year's real total (2026 for most
// countries; 2025 for Russian Federation and South Africa, which have no 2026 figure yet) --
// earlier versions instead held annual NEW REGISTRATIONS constant, which let the fleet quietly
// keep growing every year regardless (Italy +4% and Spain +20% by 2041, discovered when the
// numbers were checked against real-world expectations).
// Mechanics: each future year Y, `futureNewRegProj` (total new registrations that year, BEV +
// non-BEV combined -- NOT non-BEV-only as in prior versions) is solved as exactly whatever
// replaces the vehicles aging out of the survival curve that year, so total stock never drifts:
//   futureNewRegProj(Y) = target_total - sum over cohorts c<Y of that cohort's registrations x
//                          survival(age = Y-c)
// That total is then split into BEV/non-BEV by a logistic (odds-ratio) BEV-SHARE-OF-NEW-
// REGISTRATIONS curve (share = odds/(1+odds), so it can approach but never reach 0% or 100%),
// anchored to the country's own real anchor-year share so there's no discontinuity at the
// projection boundary, with the odds-ratio's annual growth rate DECAYED on a 6-year half-life so
// near-term momentum is honored without compounding a fixed rate for 15 years straight.
// Growth-rate calibration: normally taken from the country's own real BEV-share change over its
// 2024->2026 window (2023->2026 for the Philippines, whose 2024 BEV figure wasn't usable) --
// but a country with a tiny recent BEV base produces a huge, meaningless odds-ratio growth rate
// this way (e.g. a real move from 1% to 4% share reads as +200%/yr, despite the underlying
// absolute change being tiny). For any country whose reference-year share was under 15% AND
// whose own calibrated rate exceeds a credible same-region comparator's, the comparator's rate is
// borrowed instead (never the reverse -- this only ever pulls an inflated rate down, never pushes
// a modest one up): Germany anchors Europe, China anchors Asia and also backstops Latin America
// and Oceania (which have no credible in-region comparator among the countries tracked here).
// Norway is deliberately excluded as a comparator despite its own high rate: that reflects
// near-total-saturation dynamics (already ~89% real share in the reference window), not a
// transition curve a smaller market could plausibly still be early on. Countries whose own rate
// was already reasonable (below their region's comparator) were left as calibrated: this ended up
// including Italy, Spain, Poland, Turkey, and Vietnam -- Vietnam's own elevated real rate (driven
// by domestic maker VinFast) was kept rather than borrowed, since its reference-year share (~19%)
// wasn't actually small. Per-country figures (own rate, region comparator used if any, reference
// year, target total held constant) are in country_cars_on_road's own row notes.
// MAINTENANCE: re-run this projection whenever a new month of real registration data lands for a
// tracked country -- the anchor year/total and the growth-rate calibration window both shift as
// new real data arrives, so stale future rows drift away from what the model would now say. The
// generating script lived in this session's scratchpad, not the repo; a future pass should give
// it a permanent home (e.g. a checked-in Python script) rather than re-deriving it from scratch.
//
// Registration history: BEV/total split comes from this project's own annual powertrain data
// (varies by country, as early as 2013, as late as 2023); years before that use
// auto-markets-by-country.html's MARKETS.series total-market figures (2005 onward for most
// countries, BEV assumed 0) with no independent BEV number: pre-2013 EV volume is genuinely close
// to zero almost everywhere, so this is a reasonable simplification, not a real gap. Taiwan has
// no MARKETS.series data before 2020 at all -- its 2005-2019 rows flat-backfill the 2020 figure
// rather than inventing a trend, per explicit user instruction to do this only where no real data
// could be found. Continent-to-survival-curve mapping: EU->Europe, ASIA->Asia, NAC (US/Canada)
// ->America, SA->Latam; Mexico (NAC) and South Africa (AFRICA) were mapped to Latam and Australia
